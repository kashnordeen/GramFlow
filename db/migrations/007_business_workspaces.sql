CREATE TABLE rate_ranges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id BIGINT NOT NULL DEFAULT COALESCE(NULLIF(current_setting('app.business_id', true), '')::bigint, 1) REFERENCES businesses(id),
  min_grams NUMERIC(14,3) NOT NULL CHECK (min_grams > 0),
  max_grams NUMERIC(14,3) NOT NULL CHECK (max_grams >= min_grams),
  amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  UNIQUE (business_id, min_grams, max_grams)
);
ALTER TABLE businesses ENABLE ROW LEVEL SECURITY;
CREATE POLICY gramflow_app_server_access ON businesses FOR ALL TO PUBLIC
  USING (current_user = 'gramflow_app') WITH CHECK (current_user = 'gramflow_app');
ALTER TABLE rate_ranges ENABLE ROW LEVEL SECURITY;
CREATE POLICY gramflow_business_access ON rate_ranges FOR ALL TO PUBLIC
  USING (current_user = 'gramflow_app' AND business_id = NULLIF(current_setting('app.business_id', true), '')::bigint)
  WITH CHECK (current_user = 'gramflow_app' AND business_id = NULLIF(current_setting('app.business_id', true), '')::bigint);

