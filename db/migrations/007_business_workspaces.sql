DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'customers', 'stock_batches', 'sales', 'sale_batch_assignments',
    'payments', 'settings', 'accounts', 'journal_entries', 'journal_lines', 'audit_logs'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ADD COLUMN business_id BIGINT NOT NULL DEFAULT 1 REFERENCES businesses(id)', table_name);
    EXECUTE format(
      'ALTER TABLE %I ALTER COLUMN business_id SET DEFAULT COALESCE(NULLIF(current_setting(''app.business_id'', true), '''')::bigint, 1)',
      table_name
    );
    EXECUTE format('DROP POLICY gramflow_app_server_access ON %I', table_name);
    EXECUTE format(
      'CREATE POLICY gramflow_business_access ON %I FOR ALL TO PUBLIC USING (current_user = ''gramflow_app'' AND business_id = COALESCE(NULLIF(current_setting(''app.business_id'', true), '''')::bigint, 1)) WITH CHECK (current_user = ''gramflow_app'' AND business_id = COALESCE(NULLIF(current_setting(''app.business_id'', true), '''')::bigint, 1))',
      table_name
    );
  END LOOP;
END $$;

